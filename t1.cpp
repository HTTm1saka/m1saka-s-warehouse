// 这一行叫做"头文件包含"。
// iostream 是 "Input Output Stream"（输入输出流）的缩写，
// 里面包含了 cout（输出）和 cin（输入）等工具。
#include <iostream>

// main 是"主函数"，每个 C++ 程序都从这里开始执行。
// int 表示这个函数结束时返回一个整数（返回 0 表示程序正常结束）。
int main()
{
    // cout 是"console output"（控制台输出）的意思。
    // << 是"插入运算符"，把右边的内容送到左边的输出流里。
    // endl 是"end line"（换行），相当于按一次回车。
    // 末尾的分号 ; 是必须的，表示一条语句结束。
    std::cout << "Hello, World!" << std::endl;

    // 顺便多输出几行，让你熟悉一下用法
    std::cout << "你好，世界！" << std::endl;
    std::cout << "我开始学习 C++ 啦！" << std::endl;

    // 返回 0，告诉操作系统"程序正常结束了"。
    return 0;
}

